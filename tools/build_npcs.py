#!/usr/bin/env python3
"""Build Data/NPCs_Recorded.lua from tools/overrides/npcs_ingame.json.

That file is filled by tools/import_scans.py from what players recorded in game: where
trainers and vendors stand, which ranks a trainer teaches, and what a vendor sells.
The addon merges these records over the hand-written Data/NPCs.lua when it loads, so a
recorded position or skill cap replaces the Classic-era guess.

Usage (from the repo root):
    python tools/build_npcs.py
"""

import json

from build_recipes import ROOT, lua_string


def main():
    path = ROOT / "tools" / "overrides" / "npcs_ingame.json"
    npcs = json.loads(path.read_text(encoding="utf-8"))["npcs"] if path.exists() else {}
    lines = [
        "-- Data/NPCs_Recorded.lua: trainers and vendors recorded in game by players.",
        "-- GENERATED by tools/build_npcs.py from tools/overrides/npcs_ingame.json. Do not edit by hand.",
        "-- Merged over Data/NPCs.lua when the addon loads (see Navigation.lua).",
        "-- sells = { [itemID] = price in copper for one item }, gold prices only;",
        "-- limited = items the vendor only has a few of at a time.",
        "",
        "local _, ns = ...",
        "",
        "ns.Data.RecordedNPCs = {",
    ]
    trainers = vendors = 0
    for npc_id, npc in sorted(npcs.items(), key=lambda item: int(item[0])):
        if not (npc.get("name") and npc.get("mapID") and npc.get("x") and npc.get("y")):
            continue
        head = (f"  {{ npcID = {npc_id}, name = {lua_string(npc['name'])}, role = {lua_string(npc['role'])}, "
                f"faction = {lua_string(npc.get('faction') or '')}, mapID = {npc['mapID']}, "
                f"x = {npc['x']}, y = {npc['y']}, zone = {lua_string(npc.get('zone') or '')},")
        if npc["role"] == "trainer":
            trainers += 1
            professions = ", ".join(lua_string(p) for p in npc.get("professions", []))
            cap = npc.get("maxSkill")
            lines += [head, f"    professions = {{ {professions} }}, maxSkill = {cap if cap else 'nil'} }},"]
        else:
            sold = [i for i in npc.get("items", []) if not i.get("notGold") and i.get("price")]
            if not sold:
                continue
            vendors += 1
            sells = ", ".join(f"[{i['itemID']}] = {max(1, round(i['price'] / max(1, i.get('stack', 1))))}" for i in sold)
            limited = ", ".join(f"[{i['itemID']}] = true" for i in sold if i.get("limited"))
            lines += [head, f"    sells = {{ {sells} }}, limited = {{ {limited} }} }},"]
    lines.append("}")
    out = ROOT / "Data" / "NPCs_Recorded.lua"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {out.relative_to(ROOT)}: {trainers} trainers, {vendors} vendors")


if __name__ == "__main__":
    main()
