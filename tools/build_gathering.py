#!/usr/bin/env python3
"""Build Data/Gathering.lua from tools/overrides/gathering_zockify.json.

The client has no data on where herbs, ore or fish are found, so the herbs, veins, fish, skill levels
and zones are transcribed from Zockify's WoW Forever guides. This script resolves every item name to
an item ID in the client data and fails if one is missing.

Usage (from the repo root):
    python tools/build_gathering.py --build 1.60.1.70938
"""

import argparse
import json
import re
import sys

from build_recipes import ROOT, load, lua_string


def lua_list(values):
    return "{ " + ", ".join(lua_string(v) for v in values) + " }"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--build", required=True)
    args = parser.parse_args()

    source = json.loads((ROOT / "tools" / "overrides" / "gathering_zockify.json").read_text(encoding="utf-8"))

    # Item names can repeat; prefer an ID some recipe uses as a reagent, then the lowest ID.
    used = set()
    for path in (ROOT / "Data").glob("Recipes_*.lua"):
        used.update(int(i) for i in re.findall(r"itemID = (\d+), qty", path.read_text(encoding="utf-8")))
    by_name = {}
    for row in load(args.build, "ItemSparse"):
        by_name.setdefault(row["Display_lang"], []).append(int(row["ID"]))
    missing = []

    def item_id(name):
        ids = by_name.get(name)
        if not ids:
            missing.append(name)
            return 0
        return sorted(ids, key=lambda i: (i not in used, i))[0]

    def brackets(rows):
        out = []
        for b in rows:
            parts = [f"from = {b['from']}", f"to = {b['to']}"]
            if "nodes" in b:
                parts.append(f"nodes = {lua_list(b['nodes'])}")
            for key in ("Alliance", "Horde", "both"):
                if key in b:
                    parts.append(f"{key} = {lua_list(b[key])}")
            out.append("      { " + ", ".join(parts) + " },")
        return out

    lines = [
        "-- Data/Gathering.lua: where to gather herbs, ore and fish by skill.",
        "-- GENERATED by tools/build_gathering.py from tools/overrides/gathering_zockify.json. Do not edit by hand.",
        "-- " + source["credit"] + ".",
        "",
        "local _, ns = ...",
        "",
        "ns.Data.Gathering = {",
    ]
    for profession in ("Herbalism", "Mining"):
        data = source[profession]
        lines.append(f"  [{lua_string(profession)}] = {{")
        lines.append("    nodes = {")
        for node in data["nodes"]:
            name, skill = node[0], node[1]
            item = node[2] if len(node) > 2 else name
            lines.append(f"      {{ name = {lua_string(name)}, skill = {skill}, itemID = {item_id(item)} }}, -- {item}")
        lines.append("    },")
        lines.append("    brackets = {")
        lines += brackets(data["brackets"])
        lines.append("    },")
        lines.append("  },")
    fishing = source["Fishing"]
    lines.append('  ["Fishing"] = {')
    lines.append("    fish = {")
    for name, where in fishing["fish"]:
        where_lua = lua_string(where) if where else "nil"
        lines.append(f"      {{ itemID = {item_id(name)}, where = {where_lua} }}, -- {name}")
    lines.append("    },")
    lines.append("    brackets = {")
    lines += brackets(fishing["brackets"])
    lines.append("    },")
    lines.append("  },")
    lines.append("}")

    if missing:
        sys.exit("not in the client data: " + ", ".join(missing))
    path = ROOT / "Data" / "Gathering.lua"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
