#!/usr/bin/env python3
"""Build Data/VendorPrices.lua from a hand-kept list of vendor-sold reagents.

Which items vendors sell is server-side, so the list of item IDs is curated in
tools/vendor_items.json. The price comes from the client data (ItemSparse.BuyPrice).

Usage (from the repo root):
    python tools/build_vendor_prices.py --build 1.60.1.70938
"""

import argparse
import json
import re
import sys

from build_recipes import ROOT, load, lua_string


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--build", required=True)
    args = parser.parse_args()

    wanted = json.loads((ROOT / "tools" / "vendor_items.json").read_text(encoding="utf-8"))["items"]
    items = {r["ID"]: r for r in load(args.build, "ItemSparse")}

    # Reagents a player saw a vendor selling for gold with unlimited stock are vendor items too.
    npcs_path = ROOT / "tools" / "overrides" / "npcs_ingame.json"
    if npcs_path.exists():
        reagents = set()
        for path in (ROOT / "Data").glob("Recipes_*.lua"):
            for line in re.findall(r"reagents = \{(.*)\},", path.read_text(encoding="utf-8")):
                reagents.update(int(i) for i in re.findall(r"itemID = (\d+)", line))
        for npc in json.loads(npcs_path.read_text(encoding="utf-8"))["npcs"].values():
            for item in npc.get("items", []):
                if (item["itemID"] in reagents and item["itemID"] not in wanted and item.get("price")
                        and not item.get("notGold") and not item.get("limited")):
                    wanted.append(item["itemID"])
                    print(f"added from a vendor seen in game: {item['itemID']} ({npc['name']})")
    lines = [
        "-- Data/VendorPrices.lua: vendor-sold reagents, [itemID] = buy price in copper.",
        f"-- GENERATED by tools/build_vendor_prices.py from DB2 build {args.build}. Do not edit by hand.",
        "-- The item list is curated in tools/vendor_items.json. These items are never priced from the AH.",
        "",
        "local _, ns = ...",
        "",
        "ns.Data.VendorPrices = {",
    ]
    for item_id in wanted:
        item = items.get(str(item_id))
        if not item:
            print(f"warning: item {item_id} is not in build {args.build}", file=sys.stderr)
            continue
        lines.append(f"  [{item_id}] = {item['BuyPrice']}, -- {item['Display_lang']}")
    lines += ["}", "", f"ns.Data.VendorPricesBuild = {lua_string(args.build)}"]
    path = ROOT / "Data" / "VendorPrices.lua"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {path.relative_to(ROOT)}: {len(lines) - 9} items")


if __name__ == "__main__":
    main()
